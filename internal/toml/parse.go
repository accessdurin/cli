// Package toml parses and writes TOML exactly like smol-toml 1.9.1, the
// library the TypeScript CLI uses for Codex's config.toml.
//
// The parser is a line-by-line port of smol-toml's parse (default options:
// maxDepth 1000, integers as JavaScript numbers, legacy TomlDate dates) and
// works on UTF-16 code units like the original, so it accepts and rejects
// the same documents. Results use the jsjson value model: tables are
// *jsjson.Object (with JavaScript key order, as smol-toml's plain objects
// have), arrays are jsjson.Array, strings jsjson.String, integers and floats
// jsjson.Number, booleans jsjson.Bool, and dates and times *Date.
//
// Dates go through a port of V8's Date parser (ES5 ISO format plus the
// legacy fallback that smol-toml relies on for loosely checked dates), so
// validity matches Node exactly. Known differences from smol-toml:
//   - Error carries smol-toml's message, line and column, but not the code
//     block excerpt.
//   - The few date-only values V8 reads through its legacy parser (such as
//     `1979- 5-27`) are local time in Node; here they are UTC, as with
//     TZ=UTC. Whether they are valid does not depend on the time zone.
//   - Only the default options exist (no integersAsBigInt, maxDepth, ...).
//
// Fixtures in testdata/ are generated by testdata/gen.mjs from smol-toml and
// the toml-test suite and checked by the tests.
package toml

import (
	"math"
	"strconv"
	"strings"

	"github.com/accessdurin/cli/internal/jsjson"
)

// Error is smol-toml's TomlError: a message plus the 1-based line and
// column (in UTF-16 code units) where parsing failed.
type Error struct {
	Message string
	Line    int
	Column  int
}

func (e *Error) Error() string { return "Invalid TOML document: " + e.Message }

// ParseBytes parses a file's bytes as the CLI does: readFile(path, 'utf8')
// (invalid UTF-8 becomes U+FFFD) followed by parse.
func ParseBytes(b []byte) (*jsjson.Object, error) {
	return Parse(jsjson.DecodeUTF8(b))
}

// Parse is smol-toml's parse for a string in jsjson's WTF-8 form.
func Parse(src string) (res *jsjson.Object, err error) {
	ctx := &ctx{s: jsjson.ToUTF16(src), d: 1000}
	defer func() {
		if r := recover(); r != nil {
			e, ok := r.(*Error)
			if !ok {
				panic(r)
			}
			res, err = nil, e
		}
	}()
	return ctx.parse(), nil
}

type ctx struct {
	s []uint16
	p int
	d int
}

// at is charCodeAt: -1 stands for NaN past the end.
func (c *ctx) at(i int) int {
	if i < 0 || i >= len(c.s) {
		return -1
	}
	return int(c.s[i])
}

func (c *ctx) str(from, to int) string { return jsjson.FromUTF16(c.s[from:to]) }

// fail is TomlError.x.
func (c *ctx) fail(msg string, ptr ...int) {
	p := c.p
	if len(ptr) > 0 {
		p = ptr[0]
	}
	if p > len(c.s) {
		p = len(c.s)
	}
	line, col := 1, 1
	for i := 0; i < p; i++ {
		switch {
		case c.s[i] == '\n':
			line, col = line+1, 1
		case c.s[i] == '\r' && i+1 < p && c.s[i+1] == '\n':
		default:
			col++
		}
	}
	panic(&Error{Message: msg, Line: line, Column: col})
}

// ---------------------------------------------------------------- util.js

func (c *ctx) skipComment() {
	for ; c.p < len(c.s); c.p++ {
		ch := c.at(c.p)
		if ch == '\n' {
			break
		}
		if ch == '\r' && c.at(c.p+1) == '\n' {
			c.p++
			break
		}
		if (ch < 0x20 && ch != '\t') || ch == 0x7f {
			c.fail("control characters are not allowed in comments")
		}
	}
}

func (c *ctx) skipVoid(banNewLines, banComments bool) {
	ch := -2 // undefined
	for c.p < len(c.s) {
		for c.p < len(c.s) {
			ch = c.at(c.p)
			if ch == ' ' || ch == '\t' || (!banNewLines && (ch == '\n' || (ch == '\r' && c.at(c.p+1) == '\n'))) {
				c.p++
				continue
			}
			break
		}
		if banComments || ch != '#' {
			break
		}
		c.skipComment()
	}
}

// ---------------------------------------------------------------- parse.js

const (
	typeDotted = iota
	typeExplicit
	typeArray
	typeArrayDotted
)

type meta struct {
	t int
	d bool
	i int
	c map[string]*meta
}

func newMeta(t int) *meta { return &meta{t: t, c: map[string]*meta{}} }

type peek struct {
	k string
	t *jsjson.Object
	c map[string]*meta
}

// child returns t[k] as a table (it is one whenever peekTable descends).
func child(t *jsjson.Object, k string) *jsjson.Object {
	v, _ := t.Get(k)
	o, _ := v.(*jsjson.Object)
	return o
}

func peekTable(key []string, table *jsjson.Object, m map[string]*meta, typ int) *peek {
	t := table
	var k string
	hasOwn := false
	var state *meta
	for i := 0; i < len(key); i++ {
		if i > 0 {
			var next jsjson.Value
			if hasOwn {
				next, _ = t.Get(k)
			} else {
				n := jsjson.NewObject()
				t.Set(k, n)
				next = n
			}
			if state = m[k]; state == nil {
				return nil // smol-toml would throw a TypeError here
			}
			m = state.c
			if typ == typeDotted && (state.t == typeExplicit || state.t == typeArray) {
				return nil
			}
			if state.t == typeArray {
				arr, _ := next.(jsjson.Array)
				l := len(arr) - 1
				if l < 0 || m[strconv.Itoa(l)] == nil {
					return nil
				}
				next = arr[l]
				m = m[strconv.Itoa(l)].c
			}
			var ok bool
			if t, ok = next.(*jsjson.Object); !ok {
				return nil
			}
		}
		k = key[i]
		hasOwn = t.Has(k)
		if hasOwn && m[k] != nil && m[k].t == typeDotted && m[k].d {
			return nil
		}
		if !hasOwn {
			t2 := typ
			if i < len(key)-1 && typ == typeArray {
				t2 = typeArrayDotted
			}
			m[k] = newMeta(t2)
		}
	}
	state = m[k]
	if state.t != typ && !(typ == typeExplicit && state.t == typeArrayDotted) {
		return nil
	}
	if typ == typeArray {
		if !state.d {
			state.d = true
			t.Set(k, jsjson.Array{})
		}
		arr, _ := t.Get(k)
		n := jsjson.NewObject()
		t.Set(k, append(arr.(jsjson.Array), n))
		t = n
		next := newMeta(typeExplicit)
		state.c[strconv.Itoa(state.i)] = next
		state.i++
		state = next
	}
	if state.d {
		return nil
	}
	state.d = true
	if typ == typeExplicit {
		if hasOwn {
			t = child(t, k)
		} else {
			n := jsjson.NewObject()
			t.Set(k, n)
			t = n
		}
	} else if typ == typeDotted && hasOwn {
		return nil
	}
	return &peek{k, t, state.c}
}

func (c *ctx) parse() *jsjson.Object {
	res := jsjson.NewObject()
	metaRoot := map[string]*meta{}
	tbl := res
	m := metaRoot
	if c.at(0) == 0xfeff {
		c.p++
	}
	c.skipVoid(false, false)
	for c.p < len(c.s) {
		var tmp int
		if c.at(c.p) == '[' {
			c.p++
			isTableArray := c.at(c.p) == '['
			if isTableArray {
				c.p++
			}
			tmp = c.p
			k := c.parseKey(']')
			if isTableArray {
				if c.at(c.p) != ']' {
					c.fail("expected end of table array declaration")
				}
				c.p++
			}
			typ := typeExplicit
			if isTableArray {
				typ = typeArray
			}
			p := peekTable(k, res, metaRoot, typ)
			if p == nil {
				c.fail("trying to redefine an already defined table or value", tmp)
			}
			m = p.c
			tbl = p.t
		} else {
			tmp = c.p
			k := c.parseKey('=')
			p := peekTable(k, tbl, m, typeDotted)
			if p == nil {
				c.fail("trying to redefine an already defined table or value", tmp)
			}
			c.skipVoid(true, true)
			v := c.extractValue(-2)
			p.t.Set(p.k, v)
		}
		c.skipVoid(true, false)
		if c.p < len(c.s) {
			if ch := c.at(c.p); ch != '\n' && (ch != '\r' || c.at(c.p+1) != '\n') {
				c.fail("each key-value declaration must be followed by an end-of-line")
			}
		}
		c.skipVoid(false, false)
	}
	return res
}

// ---------------------------------------------------------------- struct.js

func (c *ctx) parseKey(end int) []string {
	state := 0
	var parsed []string
	sliceStart := 0
	startPtr := c.p
	ch := c.at(c.p)
	for {
		switch {
		case ch == end:
			if state == 0 {
				c.fail("unexpected end of key")
			}
			if state == 1 {
				parsed = append(parsed, c.str(sliceStart, c.p))
			}
			c.p++
			return parsed
		case ch == '.':
			if state == 0 {
				c.fail("illegal empty bare key")
			}
			if state == 1 {
				parsed = append(parsed, c.str(sliceStart, c.p))
			}
			state = 0
		case state == 0 && (ch == '"' || ch == '\''):
			if ch == c.at(c.p+1) && ch == c.at(c.p+2) {
				c.fail("illegal quoted key: multiline strings are not allowed")
			}
			parsed = append(parsed, c.parseString())
			state = 2
			c.p--
		case ch == ' ' || ch == '\t':
			if state == 1 {
				parsed = append(parsed, c.str(sliceStart, c.p))
				state = 2
			}
		case ch < 0:
			// NaN: every comparison is false; it starts a bare key.
			if state == 0 {
				state = 1
				sliceStart = c.p
			}
		case state == 2 || (ch < 0x30 && ch != '-') || (ch > 0x39 && ch < 0x41) || (ch > 0x5a && ch < 0x61 && ch != '_') || ch > 0x7a:
			c.fail("illegal character in key")
		case state == 0:
			state = 1
			sliceStart = c.p
		}
		c.p++
		ch = c.at(c.p)
		if ch <= 0 { // NaN or "\0" end the loop (falsy)
			break
		}
	}
	c.fail("incomplete key-value: cannot find end of key", startPtr)
	return nil
}

func (c *ctx) parseInlineTable() jsjson.Value {
	startPtr := c.p
	c.p++
	res := jsjson.NewObject()
	implicit := map[*jsjson.Object]bool{} // tables created by dotted keys (not in smol-toml's `seen`)
	for c.p < len(c.s) {
		c.skipVoid(false, false)
		if c.at(c.p) == '}' {
			c.p++
			return res
		}
		var k string
		t := res
		hasOwn := false
		errPtr := c.p
		key := c.parseKey('=')
		for i := 0; i < len(key); i++ {
			if i > 0 {
				if hasOwn {
					t = child(t, k)
				} else {
					n := jsjson.NewObject()
					implicit[n] = true
					t.Set(k, n)
					t = n
				}
			}
			k = key[i]
			if hasOwn = t.Has(k); hasOwn {
				v, _ := t.Get(k)
				if o, ok := v.(*jsjson.Object); !ok || !implicit[o] {
					c.fail("trying to redefine an already defined value", errPtr)
				}
			}
		}
		if hasOwn {
			c.fail("trying to redefine an already defined value", errPtr)
		}
		c.skipVoid(true, true)
		t.Set(k, c.extractValue('}'))
		c.skipVoid(false, false)
		ch := c.at(c.p)
		c.p++
		if ch == '}' {
			return res
		}
		if ch != ',' {
			c.fail("expected comma or end of structure", c.p-1)
		}
	}
	c.fail("unfinished table", startPtr)
	return nil
}

func (c *ctx) parseArray() jsjson.Value {
	startPtr := c.p
	c.p++
	res := jsjson.Array{}
	for c.p < len(c.s) {
		c.skipVoid(false, false)
		if c.at(c.p) == ']' {
			c.p++
			return res
		}
		res = append(res, c.extractValue(']'))
		c.skipVoid(false, false)
		ch := c.at(c.p)
		c.p++
		if ch == ']' {
			return res
		}
		if ch != ',' {
			c.fail("expected comma or end of structure", c.p-1)
		}
	}
	c.fail("unfinished array", startPtr)
	return nil
}

// ---------------------------------------------------------------- extract.js

func isDigit(ch int, base int) bool {
	if base == 16 {
		return (ch > 0x2f && ch < 0x3a) || (ch > 0x40 && ch < 0x47) || (ch > 0x60 && ch < 0x67)
	}
	return ch > 0x2f && ch < 0x30+base
}

// isEndOfValue; delim -2 is undefined.
func isEndOfValue(ch, delim int) bool {
	return ch == ' ' || ch == '\t' || ch == '\n' || ch == '\r' ||
		(delim > 0 && (ch == delim || ch == ',')) || ch == '#'
}

func (c *ctx) extractValue(end int) jsjson.Value {
	errPtr := c.p
	ch := c.at(c.p)
	if ch == '[' || ch == '{' {
		if c.d == 0 {
			c.fail("document contains excessively nested structures. aborting.")
		}
		c.d--
		var v jsjson.Value
		if ch == '[' {
			v = c.parseArray()
		} else {
			v = c.parseInlineTable()
		}
		c.d++
		return v
	}
	if ch == '"' || ch == '\'' {
		return jsjson.String(c.parseString())
	}
	if ch == 't' {
		c.p++
		if c.at(c.p) != 'r' || c.at(c.p+1) != 'u' || c.at(c.p+2) != 'e' {
			c.fail("invalid value", errPtr)
		}
		c.p += 3
		return jsjson.Bool(true)
	}
	if ch == 'f' {
		c.p++
		if c.at(c.p) != 'a' || c.at(c.p+1) != 'l' || c.at(c.p+2) != 's' || c.at(c.p+3) != 'e' {
			c.fail("invalid value", errPtr)
		}
		c.p += 4
		return jsjson.Bool(false)
	}
	if ch == '+' || ch == '-' {
		sign := 0x2c - ch
		c.p++
		return c.parseNumber(c.p-1, c.at(c.p), sign, end)
	}
	if c.at(c.p+4) == '-' && c.at(c.p+7) == '-' {
		return c.parseDate(ch, end)
	}
	if c.at(c.p+2) == ':' {
		return c.parseTime(ch, end)
	}
	return c.parseNumber(c.p, ch, 0, end)
}

func (c *ctx) parseNumber(startPtr, startChr, sign, endChr int) jsjson.Value {
	ch := startChr
	state := 0
	hasUnderscores := false
	signOr1 := float64(sign)
	if sign == 0 {
		signOr1 = 1
	}
	if ch == 'i' {
		c.p++
		if c.at(c.p) != 'n' || c.at(c.p+1) != 'f' {
			c.fail("invalid value", startPtr)
		}
		c.p += 2
		return jsjson.Number(math.Inf(int(signOr1)))
	}
	if ch == 'n' {
		c.p++
		if c.at(c.p) != 'a' || c.at(c.p+1) != 'n' {
			c.fail("invalid value", startPtr)
		}
		c.p += 2
		return jsjson.Number(math.NaN())
	}
	if ch == '0' {
		c.p++
		if c.p >= len(c.s) {
			return jsjson.Number(0)
		}
		ch = c.at(c.p)
		if isEndOfValue(ch, endChr) {
			return jsjson.Number(0)
		}
		if sign == 0 {
			switch ch {
			case 'x':
				return c.parseIntegerBaseN(startPtr, 16, endChr)
			case 'b':
				return c.parseIntegerBaseN(startPtr, 2, endChr)
			case 'o':
				return c.parseIntegerBaseN(startPtr, 8, endChr)
			}
		}
		if ch == '.' {
			state = 2
		} else if ch == 'e' || ch == 'E' {
			state = 4
		} else {
			c.fail("illegal leading zero", startPtr)
		}
	} else if !isDigit(ch, 10) {
		c.fail("invalid value", startPtr)
	}
	for {
		c.p++
		if c.p >= len(c.s) {
			break
		}
		ch = c.at(c.p)
		if isEndOfValue(ch, endChr) {
			break
		}
		if state == 0 {
			state = 1
		}
		switch {
		case ch == '_':
			if state&1 == 0 {
				c.fail("illegal underscore")
			}
			state += 11
			hasUnderscores = true
		case state == 1 && ch == '.':
			state = 2
		case (state == 1 || state == 3) && (ch == 'e' || ch == 'E'):
			state = 4
		case state == 4 && (ch == '+' || ch == '-'):
			state = 6
		case !isDigit(ch, 10):
			c.fail("illegal character in numeric literal")
		case state > 9:
			state -= 11
		case state&1 == 0:
			state++
		}
	}
	if state == 0 {
		return jsjson.Number(float64(startChr-'0') * signOr1)
	}
	if state&1 == 0 {
		c.fail("unfinished numeric value", startPtr)
	}
	str := c.str(startPtr, c.p)
	if hasUnderscores {
		str = strings.ReplaceAll(str, "_", "")
	}
	if state > 1 {
		f, _ := strconv.ParseFloat(str, 64) // range errors still give ±Inf / ±0 like parseFloat
		return jsjson.Number(f)
	}
	return c.parseInteger(str, 10, startPtr)
}

func (c *ctx) parseIntegerBaseN(startPtr, base, endChr int) jsjson.Value {
	underscore := 1
	for {
		c.p++
		if c.p >= len(c.s) {
			break
		}
		ch := c.at(c.p)
		if isEndOfValue(ch, endChr) {
			break
		}
		switch {
		case ch == '_':
			if underscore&1 != 0 {
				c.fail("illegal underscore")
			}
			underscore = 3
		case !isDigit(ch, base):
			c.fail("illegal character in numeric literal")
		case underscore&1 != 0:
			underscore--
		}
	}
	if underscore&1 != 0 {
		c.fail("unfinished numeric value")
	}
	str := c.str(startPtr+2, c.p)
	if underscore != 0 {
		str = strings.ReplaceAll(str, "_", "")
	}
	return c.parseInteger(str, base, startPtr)
}

const maxSafeInteger = 1<<53 - 1

// parseInteger is parseInt(str, base) followed by Number.isSafeInteger.
func (c *ctx) parseInteger(str string, base, startPtr int) jsjson.Value {
	neg := false
	digits := str
	if base == 10 && len(digits) > 0 && (digits[0] == '+' || digits[0] == '-') {
		neg = digits[0] == '-'
		digits = digits[1:]
	}
	v, err := strconv.ParseUint(digits, base, 64)
	if err != nil || v > maxSafeInteger {
		c.fail("integer value cannot be represented losslessly", startPtr)
	}
	f := float64(v)
	if neg {
		f = -f
	}
	return jsjson.Number(f)
}

func (c *ctx) parseDate(ch, endChr int) jsjson.Value {
	startPtr := c.p
	c.p++
	unsafeSeparator := false
	if !isDigit(ch, 10) || !isDigit(c.at(c.p), 10) || !isDigit(c.at(c.p+1), 10) || !isDigit(c.at(c.p+2), 10) {
		// smol-toml advances ctx.p while checking, then resets it.
		c.p = startPtr
		return c.parseNumber(startPtr, ch, 0, endChr)
	}
	c.p += 3
	c.p += 5
	if !isDigit(c.at(c.p), 10) {
		c.p++
		c.fail("invalid date-time: date part is malformed", startPtr)
	}
	c.p++
	if c.p >= len(c.s) {
		return c.readDate(c.str(startPtr, c.p), dateLocalDate, false, startPtr)
	}
	ch = c.at(c.p)
	isTimeSep := false
	if ch == ' ' {
		unsafeSeparator = true
		isTimeSep = isDigit(c.at(c.p+1), 10)
	}
	if !isTimeSep && ch != 'T' && ch != 't' {
		return c.readDate(c.str(startPtr, c.p), dateLocalDate, false, startPtr)
	}
	c.p += 3
	if c.at(c.p) != ':' {
		c.fail("invalid date-time: time part is malformed", startPtr)
	}
	c.p += 3
	if c.at(c.p) == ':' {
		c.p += 3
	}
	if c.at(c.p) == '.' {
		for {
			c.p++
			if !isDigit(c.at(c.p), 10) {
				break
			}
		}
	}
	if ch = c.at(c.p); ch > 0 {
		if ch == 'Z' || ch == 'z' {
			c.p++
			return c.readDate(c.str(startPtr, c.p), dateOffset, unsafeSeparator, startPtr)
		}
		if ch == '+' || ch == '-' {
			end := c.p + 6
			if end > len(c.s) {
				end = len(c.s)
			}
			t := c.str(startPtr, end)
			c.p += 6
			return c.readDate(t, dateOffset, unsafeSeparator, startPtr)
		}
	}
	return c.readDate(c.str(startPtr, c.p), dateLocalDateTime, unsafeSeparator, startPtr)
}

func (c *ctx) parseTime(ch, endChr int) jsjson.Value {
	start := c.p
	if !isDigit(ch, 10) {
		// smol-toml's `--ctx.p` runs without the `++ctx.p` here.
		c.p = start - 1
		return c.parseNumber(start-1, ch, 0, endChr)
	}
	if !isDigit(c.at(c.p+1), 10) {
		return c.parseNumber(start, ch, 0, endChr)
	}
	c.p++
	c.p += 4
	if c.at(c.p) == ':' {
		c.p += 3
	}
	if c.at(c.p) == '.' {
		for {
			c.p++
			if !isDigit(c.at(c.p), 10) {
				break
			}
		}
	}
	end := c.p
	if end > len(c.s) {
		end = len(c.s)
	}
	return c.readDate(c.str(start, end), dateLocalTime, false, start)
}

func (c *ctx) readDate(str string, typ int, unsafeDelim bool, errPtr int) jsjson.Value {
	d := newTomlDate(jsjson.ToUTF16(str), typ, unsafeDelim)
	if d == nil {
		c.fail("invalid date", errPtr)
	}
	return d
}

