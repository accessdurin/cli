func (c *ctx) parseString() string {
	startPtr := c.p
	ch := c.at(c.p)
	c.p++
	first := ch
	isLiteral := ch == '\''
	isMultiline := ch == c.at(c.p) && ch == c.at(c.p+1)
	if isMultiline {
		c.p += 2
		if ch = c.at(c.p); ch == '\n' {
			c.p++
		} else if ch == '\r' && c.at(c.p+1) == '\n' {
			c.p += 2
		}
	}
	var parsed []uint16
	sliceStart := c.p
	state := 0
	for ; c.p < len(c.s); c.p++ {
		ch = c.at(c.p)
		switch {
		case isMultiline && (ch == '\n' || (ch == '\r' && c.at(c.p+1) == '\n')):
			if state != 0 {
				state = 3
			}
		case (ch < 0x20 && ch != '\t') || ch == 0x7f:
			c.fail("control characters are not allowed in strings")
		case (state == 0 || state == 3) && ch == first && (!isMultiline || (c.at(c.p+1) == first && c.at(c.p+2) == first)):
			if isMultiline {
				if c.at(c.p+3) == first {
					c.p++
				}
				if c.at(c.p+3) == first {
					c.p++
				}
			}
			if state == 0 {
				parsed = append(parsed, c.s[sliceStart:c.p]...)
			}
			if isMultiline {
				c.p += 3
			} else {
				c.p++
			}
			return jsjson.FromUTF16(parsed)
		case state == 0:
			if !isLiteral && ch == '\\' {
				parsed = append(parsed, c.s[sliceStart:c.p]...)
				sliceStart = c.p
				state = 1
			}
		case state == 1:
			if ch == 'x' || ch == 'u' || ch == 'U' {
				errPtr := c.p - 1
				c.p++
				var value uint32
				n := 8
				if ch == 'x' {
					n = 2
				} else if ch == 'u' {
					n = 4
				}
				for j := 0; j < n; j, c.p = j+1, c.p+1 {
					hex := c.at(c.p)
					digit := -1
					switch {
					case hex >= '0' && hex <= '9':
						digit = hex - '0'
					case hex >= 'A' && hex <= 'F':
						digit = hex - 'A' + 10
					case hex >= 'a' && hex <= 'f':
						digit = hex - 'a' + 10
					}
					if digit < 0 {
						c.fail("invalid non-hex character in unicode escape")
					}
					value = value<<4 | uint32(digit)
				}
				if value > 0x10ffff || (value >= 0xd800 && value <= 0xdfff) {
					c.fail("invalid unicode escape", errPtr)
				}
				if value >= 0x10000 {
					v := value - 0x10000
					parsed = append(parsed, uint16(0xd800+(v>>10)), uint16(0xdc00+(v&0x3ff)))
				} else {
					parsed = append(parsed, uint16(value))
				}
				sliceStart = c.p
				c.p--
				state = 0
			} else if isMultiline && (ch == ' ' || ch == '\t') {
				state = 2
			} else {
				var e uint16
				switch ch {
				case 'b':
					e = '\b'
				case 't':
					e = '\t'
				case 'n':
					e = '\n'
				case 'f':
					e = '\f'
				case 'r':
					e = '\r'
				case 'e':
					e = 0x1b
				case '"':
					e = '"'
				case '\\':
					e = '\\'
				default:
					c.fail("unrecognised escape sequence")
				}
				parsed = append(parsed, e)
				sliceStart = c.p + 1
				state = 0
			}
		case ch != ' ' && ch != '\t':
			if state == 2 {
				c.fail("invalid escape: only line-ending whitespace may be escaped", sliceStart)
			}
			if !isLiteral && ch == '\\' {
				state = 1
			} else {
				state = 0
			}
			sliceStart = c.p
		}
	}
	c.fail("unfinished string", startPtr)
	return ""
}
