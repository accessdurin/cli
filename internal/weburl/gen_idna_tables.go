// Command gen_idna_tables writes idna_tables.go from the IDNA tables of ada, the URL parser
// Node.js uses, so that domain-to-ASCII here makes exactly the decisions Node 22 makes.
//
//	go run gen_idna_tables.go [path/to/ada_idna.cpp]
//
// Without a path it fetches src/ada_idna.cpp from github.com/ada-url/ada at adaVersion,
// the version process.versions.ada reports in Node 22 (see testdata/parse.json's meta).
