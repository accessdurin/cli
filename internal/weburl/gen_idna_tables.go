func main() {
	src := load()
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by gen_idna_tables.go from ada %s src/ada_idna.cpp; DO NOT EDIT.\n\n", adaVersion)
	out.WriteString(adaNotice)
	out.WriteString("package weburl\n\n")

	writeList(&out, "idnaMappings", "uint32", numbers(block(src, "const uint32_t mappings[")))

	pairs := numbers(block(src, "const uint32_t table["))
	if len(pairs)%2 != 0 {
		log.Fatal("odd table length")
	}
	fmt.Fprintf(&out, "var idnaTable = [...][2]uint32{\n")
	for i := 0; i < len(pairs); i += 2 {
		fmt.Fprintf(&out, "{%s, %s},", pairs[i], pairs[i+1])
		if i%16 == 14 {
			out.WriteString("\n")
		}
	}
	out.WriteString("}\n\n")

	dirs := block(src, "static directions dir_table[]")
	entry := regexp.MustCompile(`\{(0x[0-9a-fA-F]+),\s*(0x[0-9a-fA-F]+),\s*direction::([A-Z]+)\}`)
	fmt.Fprintf(&out, "var idnaDirTable = [...]dirRange{\n")
	n := 0
	for _, m := range entry.FindAllStringSubmatch(dirs, -1) {
		fmt.Fprintf(&out, "{%s, %s, dir%s},", m[1], m[2], m[3])
		n++
		if n%4 == 0 {
			out.WriteString("\n")
		}
	}
	out.WriteString("}\n\n")

	for _, name := range []string{"combining", "virama", "R", "L", "D"} {
		writeList(&out, "idna"+strings.ToUpper(name[:1])+name[1:], "uint32",
			numbers(block(src, "constexpr static uint32_t "+name+"[]")))
	}

	formatted, err := format.Source(out.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("idna_tables.go", formatted, 0o644); err != nil {
		log.Fatal(err)
	}
}

func load() string {
	if len(os.Args) > 1 {
		b, err := os.ReadFile(os.Args[1])
		if err != nil {
			log.Fatal(err)
		}
		return string(b)
	}
	url := "https://raw.githubusercontent.com/ada-url/ada/" + adaVersion + "/src/ada_idna.cpp"
	resp, err := http.Get(url)
	if err != nil {
		log.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		log.Fatalf("%s: %s", url, resp.Status)
	}
	b, err := io.ReadAll(resp.Body)
	if err != nil {
		log.Fatal(err)
	}
	return string(b)
}

// block returns the brace-delimited initializer that follows the first occurrence of decl.
func block(src, decl string) string {
	i := strings.Index(src, decl)
	if i < 0 {
		log.Fatalf("%q not found", decl)
	}
	start := strings.Index(src[i:], "{") + i
	depth := 0
	for j := start; j < len(src); j++ {
		switch src[j] {
		case '{':
			depth++
		case '}':
			depth--
			if depth == 0 {
				return src[start+1 : j]
			}
		}
	}
	log.Fatalf("%q: unterminated", decl)
	return ""
}

var number = regexp.MustCompile(`\b(0x[0-9a-fA-F]+|[0-9]+)\b`)

func numbers(s string) []string {
	var out []string
	for _, m := range number.FindAllString(s, -1) {
		v, err := strconv.ParseUint(m, 0, 32)
		if err != nil {
			log.Fatal(err)
		}
		out = append(out, strconv.FormatUint(v, 10))
	}
	return out
}

func writeList(out *bytes.Buffer, name, typ string, values []string) {
	fmt.Fprintf(out, "var %s = [...]%s{\n", name, typ)
	for i, v := range values {
		out.WriteString(v)
		out.WriteString(",")
		if i%16 == 15 {
			out.WriteString("\n")
		}
	}
	out.WriteString("}\n\n")
}
