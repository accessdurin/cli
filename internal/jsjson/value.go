// Package jsjson is a JSON value model and codec that reproduces JavaScript
// semantics byte for byte: JSON.parse, JSON.stringify (with and without
// indentation), the key order of JavaScript objects, JavaScript's
// Number-to-string conversion, and strings that may hold lone surrogates.
//
// Values are one of Null, Bool, Number, String, Array, *Object, or a type
// embedding Extension that implements JSONer. A nil Value stands for
// JavaScript's undefined: JSON.stringify omits it as an object member and
// writes null for it inside an array.
//
// Strings are WTF-8; see the comment at the top of strings.go.
//
// Fixtures in testdata/ are generated by testdata/gen.mjs from Node 22 and
// checked by the tests. Known differences from JavaScript:
//   - SyntaxError messages are not V8's; only acceptance matches.
//   - Stringify of a top-level undefined (nil) returns "" where JavaScript
//     returns undefined.
//   - JSON.stringify throws on cyclic values and on nesting deep enough to
//     overflow V8's stack; Stringify recurses without a limit (a cycle never
//     terminates). JSON.parse has no practical depth limit, nor does Parse.
//   - Replacers, toJSON on ordinary objects, BigInt and getters do not
//     exist here; Extension is the only toJSON hook.
package jsjson

import (
	"math"
	"sort"
)

// Value is a JavaScript value that JSON can represent.
type Value interface{ jsValue() }

// Null is JavaScript's null.
type Null struct{}

// Bool is a JavaScript boolean.
type Bool bool

// Number is a JavaScript number (an IEEE 754 double).
type Number float64

// String is a JavaScript string in WTF-8 form.
type String string

// Array is a JavaScript array. A nil element is undefined (written as null).
type Array []Value

func (Null) jsValue()    {}
func (Bool) jsValue()    {}
func (Number) jsValue()  {}
func (String) jsValue()  {}
func (Array) jsValue()   {}
func (*Object) jsValue() {}

// Extension may be embedded by types outside this package to make them a
// Value. Such a value behaves like a JavaScript object with a toJSON method
// (Date, for instance): it must implement JSONer, Stringify writes what
// ToJSON returns, and CanonicalJSON writes {} because canonicalJson only
// copies own enumerable keys, of which such objects have none.
type Extension struct{}

func (Extension) jsValue() {}

// JSONer is a value with a JavaScript toJSON method.
type JSONer interface {
	Value
	ToJSON() Value
}

// Object is a JavaScript object with JavaScript's own-key order: keys that
// are array indices ("0", "1", ... "4294967294" in canonical form) come
// first in ascending numeric order, all other keys follow in insertion order.
// The zero value is an empty object ready to use.
type Object struct {
	keys []string
	vals map[string]Value
	nIdx int // keys[:nIdx] are array indices
}

// NewObject returns an empty object.
func NewObject() *Object { return &Object{} }

// Member is a key and value pair used to build objects.
type Member struct {
	Key   string
	Value Value
}

// Obj builds an object by setting members in order, like an object literal.
func Obj(members ...Member) *Object {
	o := &Object{}
	for _, m := range members {
		o.Set(m.Key, m.Value)
	}
	return o
}

// KV is shorthand for a Member.
func KV(key string, v Value) Member { return Member{key, v} }

// arrayIndex reports whether key is a canonical array index and returns it.
func arrayIndex(key string) (uint32, bool) {
	n := len(key)
	if n == 0 || n > 10 || (n > 1 && key[0] == '0') {
		return 0, false
	}
	var v uint64
	for i := 0; i < n; i++ {
		c := key[i]
		if c < '0' || c > '9' {
			return 0, false
		}
		v = v*10 + uint64(c-'0')
	}
	if v > math.MaxUint32-1 {
		return 0, false
	}
	return uint32(v), true
}

// Set assigns o[key] = v. An existing key keeps its position. It returns o.
func (o *Object) Set(key string, v Value) *Object {
	if o.vals == nil {
		o.vals = map[string]Value{}
	}
	if _, ok := o.vals[key]; ok {
		o.vals[key] = v
		return o
	}
	o.vals[key] = v
	if idx, ok := arrayIndex(key); ok {
		at := sort.Search(o.nIdx, func(i int) bool {
			j, _ := arrayIndex(o.keys[i])
			return j > idx
		})
		o.keys = append(o.keys, "")
		copy(o.keys[at+1:], o.keys[at:])
		o.keys[at] = key
		o.nIdx++
		return o
	}
	o.keys = append(o.keys, key)
	return o
}

// Get returns o[key] and whether the key exists.
func (o *Object) Get(key string) (Value, bool) {
	if o == nil {
		return nil, false
	}
	v, ok := o.vals[key]
	return v, ok
}

// Has reports whether key is an own key of o.
func (o *Object) Has(key string) bool {
	_, ok := o.Get(key)
	return ok
}

// Delete removes key, like the delete operator, and reports whether it existed.
func (o *Object) Delete(key string) bool {
	if !o.Has(key) {
		return false
	}
	delete(o.vals, key)
	for i, k := range o.keys {
		if k == key {
			o.keys = append(o.keys[:i], o.keys[i+1:]...)
			if i < o.nIdx {
				o.nIdx--
			}
			break
		}
	}
	return true
}

// Len returns the number of own keys.
func (o *Object) Len() int {
	if o == nil {
		return 0
	}
	return len(o.keys)
}

// Keys returns the own keys in JavaScript order, like Object.keys.
func (o *Object) Keys() []string {
	if o == nil {
		return nil
	}
	return append([]string(nil), o.keys...)
}

// Members returns the entries in JavaScript order, like Object.entries.
func (o *Object) Members() []Member {
	if o == nil {
		return nil
	}
	out := make([]Member, len(o.keys))
	for i, k := range o.keys {
		out[i] = Member{k, o.vals[k]}
	}
	return out
}

// Range calls f for each member in order until f returns false.
func (o *Object) Range(f func(key string, v Value) bool) {
	if o == nil {
		return
	}
	for _, k := range o.Keys() {
		if !f(k, o.vals[k]) {
			return
		}
	}
}

// Clone returns a shallow copy of o, like {...o}.
func (o *Object) Clone() *Object {
	c := &Object{}
	if o == nil {
		return c
	}
	c.keys = append([]string(nil), o.keys...)
	c.nIdx = o.nIdx
	c.vals = make(map[string]Value, len(o.vals))
	for k, v := range o.vals {
		c.vals[k] = v
	}
	return c
}

// Assign copies the members of src into o in order, like Object.assign(o, src),
// and returns o.
func (o *Object) Assign(src *Object) *Object {
	for _, m := range src.Members() {
		o.Set(m.Key, m.Value)
	}
	return o
}

// GetString returns o[key] if it is a string.
func (o *Object) GetString(key string) (string, bool) {
	v, _ := o.Get(key)
	s, ok := v.(String)
	return string(s), ok
}

// GetNumber returns o[key] if it is a number.
func (o *Object) GetNumber(key string) (float64, bool) {
	v, _ := o.Get(key)
	n, ok := v.(Number)
	return float64(n), ok
}

// GetBool returns o[key] if it is a boolean.
func (o *Object) GetBool(key string) (bool, bool) {
	v, _ := o.Get(key)
	b, ok := v.(Bool)
	return bool(b), ok
}

// GetObject returns o[key] if it is an object.
func (o *Object) GetObject(key string) (*Object, bool) {
	v, _ := o.Get(key)
	m, ok := v.(*Object)
	return m, ok && m != nil
}

// GetArray returns o[key] if it is an array.
func (o *Object) GetArray(key string) (Array, bool) {
	v, _ := o.Get(key)
	a, ok := v.(Array)
	return a, ok
}

// Int returns a Number for an integer.
func Int(n int64) Number { return Number(float64(n)) }

// Strings returns an array of strings.
func Strings(ss ...string) Array {
	a := make(Array, len(ss))
	for i, s := range ss {
		a[i] = String(s)
	}
	return a
}

// Arr returns an array of the given values.
func Arr(vs ...Value) Array { return Array(vs) }

// TypeOf returns the JavaScript typeof of v ("undefined" for nil, "object"
// for null, arrays, objects and extensions).
func TypeOf(v Value) string {
	switch v.(type) {
	case nil:
		return "undefined"
	case Bool:
		return "boolean"
	case Number:
		return "number"
	case String:
		return "string"
	}
	return "object"
}

// Equal reports whether a and b are deeply equal JSON values with the same
// key order, i.e. whether Stringify(a) == Stringify(b) would hold for
// non-extension values; extensions compare by their ToJSON values. Numbers
// compare with ===, so NaN != NaN and 0 == -0.
func Equal(a, b Value) bool {
	switch x := a.(type) {
	case nil:
		return b == nil
	case Null, Bool, String:
		return a == b
	case Number:
		y, ok := b.(Number)
		return ok && x == y
	case Array:
		y, ok := b.(Array)
		if !ok || len(x) != len(y) {
			return false
		}
		for i := range x {
			if !Equal(x[i], y[i]) {
				return false
			}
		}
		return true
	case *Object:
		y, ok := b.(*Object)
		if !ok || x.Len() != y.Len() {
			return false
		}
		for i, k := range x.keys {
			if y.keys[i] != k || !Equal(x.vals[k], y.vals[k]) {
				return false
			}
		}
		return true
	case JSONer:
		y, ok := b.(JSONer)
		return ok && Equal(x.ToJSON(), y.ToJSON())
	}
	return false
}
