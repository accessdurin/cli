// Command syncskills bundles the Durin agent skills from a reviewed, committed checkout of
// github.com/accessdurin/skills into internal/app/skill_bundle.go. End-user setup never
// fetches instructions; maintainers run this and review the diff.
//
//	go run ./tools/syncskills [../skills]
package main

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

var skillName = regexp.MustCompile(`^durin-[a-z0-9-]+$`)

func main() {
	source := "../skills"
	if len(os.Args) > 1 {
		source = os.Args[1]
	}
	revision := strings.TrimSpace(git(source, "rev-parse", "HEAD"))
	if git(source, "status", "--porcelain") != "" {
		fail("Commit the reviewed skills snapshot before syncing.")
	}
	entries, err := os.ReadDir(filepath.Join(source, "skills"))
	check(err)
	var names []string
	for _, entry := range entries {
		names = append(names, entry.Name())
	}
	sort.Strings(names)
	license, err := os.ReadFile(filepath.Join(source, "LICENSE"))
	check(err)

	var b strings.Builder
	b.WriteString("// Code generated by tools/syncskills from a reviewed checkout of the skills repository;\n// DO NOT EDIT. Run `go run ./tools/syncskills <checkout>` to update.\n\npackage app\n\n")
	b.WriteString("// skillSource is where the bundled skills come from.\nvar skillSource = struct{ Repository, Revision string }{\n")
	fmt.Fprintf(&b, "\tRepository: %q,\n\tRevision:   %q,\n}\n\n", "https://github.com/accessdurin/skills", revision)
	fmt.Fprintf(&b, "// skillLicense is the skills repository's license, installed beside each skill.\nconst skillLicense = %s\n\n", strconv.Quote(string(license)))
	b.WriteString("type bundledSkill struct{ Name, Content, SHA256 string }\n\n// bundledSkills are the Durin agent skills, byte for byte as reviewed.\nvar bundledSkills = []bundledSkill{\n")
	for _, name := range names {
		if !skillName.MatchString(name) {
			fail("Invalid Durin skill name.")
		}
		content, err := os.ReadFile(filepath.Join(source, "skills", name, "SKILL.md"))
		check(err)
		if !strings.HasPrefix(string(content), "---\nname: "+name+"\n") {
			fail("Invalid skill: " + name)
		}
		sum := sha256.Sum256(content)
		fmt.Fprintf(&b, "\t{\n\t\tName:    %q,\n\t\tContent: %s,\n\t\tSHA256:  %q,\n\t},\n", name, strconv.Quote(string(content)), hex.EncodeToString(sum[:]))
	}
	b.WriteString("}\n")
	check(os.WriteFile(filepath.Join("internal", "app", "skill_bundle.go"), []byte(b.String()), 0o644))
	fmt.Printf("Bundled %d skills from %s.\n", len(names), revision)
}

func git(dir string, args ...string) string {
	out, err := exec.Command("git", append([]string{"-C", dir}, args...)...).Output()
	check(err)
	return string(out)
}

func check(err error) {
	if err != nil {
		fail(err.Error())
	}
}

func fail(message string) {
	fmt.Fprintln(os.Stderr, message)
	os.Exit(1)
}
