#!/usr/bin/env node
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { resolve, join } from 'node:path';

// Maintainers sync a reviewed checkout; end-user setup never fetches instructions.
const source = resolve(process.argv[2] ?? '../skills');
const revision = execFileSync('git', ['-C', source, 'rev-parse', 'HEAD'], {
  encoding: 'utf8',
}).trim();
const dirty = execFileSync('git', ['-C', source, 'status', '--porcelain'], { encoding: 'utf8' });
if (dirty) throw new Error('Commit the reviewed skills snapshot before syncing.');
const names = (await readdir(join(source, 'skills'))).toSorted();
const skills = await Promise.all(
  names.map(async (name) => {
    if (!/^durin-[a-z0-9-]+$/u.test(name)) throw new Error('Invalid Durin skill name.');
    const content = await readFile(join(source, 'skills', name, 'SKILL.md'), 'utf8');
    if (!content.startsWith(`---\nname: ${name}\n`)) throw new Error(`Invalid skill: ${name}`);
    return { name, content, sha256: createHash('sha256').update(content).digest('hex') };
  }),
);
const sourceInfo = { repository: 'https://github.com/accessdurin/skills', revision };
await writeFile(
  'src/skill-bundle.ts',
  `// Generated by scripts/sync-skills.mjs from a reviewed checkout.\nexport const skillSource = ${JSON.stringify(sourceInfo)} as const;\nexport const bundledSkills = ${JSON.stringify(skills)} as const;\n`,
);
console.log(`Bundled ${skills.length} skills from ${revision}.`);
